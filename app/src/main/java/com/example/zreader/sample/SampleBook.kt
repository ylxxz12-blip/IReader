第一章 龟兔赛跑

有一天，兔子在山坡上碰见了乌龟，便嘲笑他爬得太慢。
One day, a hare happened to meet a tortoise on the hillside and laughed at him for crawling so slowly.
乌龟很不服气，便提出和兔子赛跑，看谁先到达山脚下的大树。
The tortoise, quite unpersuaded, proposed a race with the hare to see who would first reach the great tree at the foot of the hill.
兔子满口答应，心想自己随便跑几步就能赢。
The hare agreed at once, thinking that a few casual strides would easily win him the race.
比赛开始后，兔子一溜烟跑得没影了，乌龟却一步一步不停地向前爬。
When the race began, the hare darted off in a flash, while the tortoise kept crawling forward, one steady step after another.
兔子回头一看，乌龟还远远落在后面，便决定在路边睡上一觉。
Looking back and seeing the tortoise far behind, the hare decided to take a nap by the roadside.
等兔子醒来时，乌龟早已到达了终点。
By the time the hare awoke, the tortoise had long since crossed the finish line.

第二章 下金蛋的鹅

从前，有个农夫养了一只鹅，每天都能下一个金蛋。
Once upon a time, a farmer kept a goose that laid a golden egg every day.
日子久了，农夫渐渐贪心起来，嫌一天只有一个蛋太慢。
As days went by, the farmer grew greedy, complaining that one egg a day was far too slow.
他想，鹅的肚子里一定装满了金子，不如一次全都取出来。
He supposed that the goose must be stuffed with gold inside, and thought he might as well take it all at once.
于是他杀了鹅，剖开肚子，结果里面和普通的鹅一模一样。
So he killed the goose and cut her open, only to find her just like any other goose inside.
从那以后，他连一天一个的金蛋也没有了。
From that day on, he had not even a single golden egg any more.

第三章 口渴的乌鸦

一只乌鸦口渴了，到处找水喝。
A crow, feeling very thirsty, flew here and there in search of water.
他看见一个瓶子，瓶里有水，可是瓶口很小，水又很浅，怎么也喝不着。
He came upon a pitcher with some water in it, but the neck was narrow and the water lay so low that he could not reach it at all.
乌鸦试了几次都失败了，但他没有放弃。
The crow tried again and again, and though he failed each time, he did not give up.
后来，他衔来许多小石子，一颗一颗投进瓶里。
Then he picked up pebbles one by one and dropped them into the pitcher.
水面渐渐升高，乌鸦痛快地喝了个够。
The water rose little by little, and at last the crow drank to his heart's content.

第四章 蚂蚁和蚱蜢

夏天的时候，蚂蚁们顶着烈日，忙着把粮食搬回洞里。
In summer, while the sun blazed, the ants were busy carrying food back to their nest.
蚱蜢却在草丛里又唱又跳，笑话蚂蚁不知享受。
The grasshopper, however, sang and danced among the grass, mocking the ants for knowing no enjoyment.
蚂蚁回答道：现在流点汗，冬天才不会挨饿。
The ants replied: if we sweat a little now, we shall not go hungry in winter.
蚱蜢不以为然，继续玩了一个夏天。
The grasshopper shrugged it off and played the whole summer away.
冬天来了，大雪封住了田野，蚱蜢找不到一点吃的，这才后悔起来。
When winter came and snow covered the fields, the grasshopper could find nothing to eat, and only then did he regret.

第五章 狼来了

有个放羊的孩子，喜欢恶作剧。
There was a shepherd boy who was fond of playing tricks.
他两次大喊狼来了，村里的人都赶来救他，却发现上了当。
Twice he cried out that a wolf had come, and twice the villagers rushed to help him, only to find they had been fooled.
后来狼真的来了，孩子拼命呼救，却再也没有人相信他。
Later a wolf really did come; the boy shouted with all his might, but no one believed him any more.
这个故事告诉我们，说谎的人即使说了真话，也没有人会相信。
This story tells us that even when a liar speaks the truth, no one will believe him.

第六章 北风和太阳

北风和太阳争论谁的本领更大。
The north wind and the sun argued about which of them was the stronger.
他们约定，谁能让路上的行人脱下外套，就算谁赢。
They agreed that whoever could make a traveler take off his coat should be counted the winner.
北风呼呼地吹，行人却把外套裹得更紧了。
The north wind blew with all his might, but the traveler only wrapped his coat more tightly around him.
太阳出来，暖洋洋地照着，行人很快就脱下了外套。
Then the sun shone out warm and bright, and the traveler soon took off his coat.
温和的力量，往往比强迫更有效。
Gentleness and persuasion are often more effective than force.
